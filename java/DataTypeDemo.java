public class DataTypeDemo {
    public static void main(String[] args) {
        int i = 42;
        float f = 3.14f;
        double d = 2.71828;
        char c = 'J';
        boolean b = true;
        System.out.println("int: " + i + ", float: " + f + ", double: " + d + ", char: " + c + ", boolean: " + b);
    }
}
